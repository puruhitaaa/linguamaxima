export type NestedKeyOf<T> = {
  [K in keyof T & (string | number)]: T[K] extends Record<string, unknown>
    ? `${K}.${NestedKeyOf<T[K]>}`
    : `${K}`;
}[keyof T & (string | number)];

export type TranslationKey = NestedKeyOf<TranslationDictionary>;
